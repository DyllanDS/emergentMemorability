function run_module()
%RUN_MODULE  Module 05, the THINGS feature reanalysis (Fig. 5): entry point of the MATLAB part.
%
% WHAT IT DOES
%   1. things_reanalysis.m: Figs. 5a to 5d, the two correlations of Figs. 5c and 5d (r = -0.612
%      human, r = -0.296 monkey) and their check against the saved run in data/paper_run/.
%   2. monkey_variance_explained.m: the percent of variance the 49 monkey IT components keep
%      (Methods, Representational Similarity Analysis).
%   3. Writes outputs/numbers.csv: one row per ledger item computed in steps 1 and 2 (the printed
%      value, location and quote come from shared/ledger/paper_numbers.csv through
%      shared/matlab/write_numbers_csv.m, which also judges the match). The run stops if a judged
%      value does not match the value printed in the paper.
%   The bootstrap statistics (the 95% intervals and p values of Figs. 5c and 5d, outputs/tests.csv)
%   come from the Python script code/stats_fig5.py, which writes their rows of outputs/numbers.csv
%   (L3-009, L3-010, L3-012, L3-013, L3-101 and L4-004). Each part keeps the rows the other wrote,
%   so the two can run in either order.
%   Everything the run prints is also written to outputs/logs/run_module.log.
%
% HOW TO RUN (from the repository root)
%   matlab -batch "restoredefaultpath; cd('05_things_reanalysis_fig5/code'); run_module"
%   python 05_things_reanalysis_fig5/code/stats_fig5.py
% Runtime: under a minute (MATLAB R2023b, Statistics and Machine Learning Toolbox; no parallel pool).

codeFolder = fileparts(mfilename('fullpath'));
addpath(codeFolder);
addpath(fullfile(codeFolder, '..', '..', 'shared', 'matlab'));
paths = release_paths(mfilename('fullpath'));
scriptName = 'code/things_reanalysis.m';

%% 0. The run log (outputs/logs/run_module.log, rewritten on every run)
logFile = fullfile(paths.logs, 'run_module.log');
if exist(logFile, 'file')
    delete(logFile);
end
diary(logFile);
stopTheLogAtTheEnd = onCleanup(@() diary('off'));
fprintf('Module 05, THINGS feature reanalysis (Fig. 5); MATLAB %s\n', version);

%% 1. The analysis and the figures
fig5 = things_reanalysis();

%% 2. Variance kept by the 49 monkey components
monkeyVariance = monkey_variance_explained();

%% 3. Values the rows below quote
labels = fig5.featureLabels;
numberOfFeatures = fig5.numberOfFeatures;
memorabilityRanks = ranks_from_highest(fig5.memorabilityCorrelationsHuman);
similarityRanks = ranks_from_lowest(fig5.summedSimilarityCorrelationsHuman);

bodyPart = find(strcmp(labels, 'body part-related'));
electronics = find(strcmp(labels, 'electronic / technology'));
[~, mostMemorable] = max(fig5.memorabilityCorrelationsHuman);
[~, leastMemorable] = min(fig5.memorabilityCorrelationsHuman);
[~, similarityOrder] = sort(fig5.summedSimilarityCorrelationsHuman, 'ascend');   % most negative first
mostPositiveSimilarity = similarityOrder(end);

%% 4. One row per ledger item computed here
% (the script column names the script that computes the value: code/things_reanalysis.m, unless a
% row gives another one; code/stats_fig5.py adds the rows of the bootstrap statistics)
rows = struct('ledger_id', {}, 'computed_value', {}, 'mode', {}, 'note', {}, 'script', {});

rows(end + 1) = numbers_row('L3-001', numberOfFeatures, 'rerun', ...
    'Number of SPoSE features: the columns of the 1,854 x 49 embedding.');
rows(end + 1) = numbers_row('L3-002', sprintf(['human RDM %d x %d (correlations of the %d SPoSE features, ' ...
    'from %.3f to %.3f); monkey RDM %d x %d (correlations of the %d IT components, from %.3f to %.3f)'], ...
    fig5.similarityMatrixSizeHuman(1), fig5.similarityMatrixSizeHuman(2), numberOfFeatures, ...
    fig5.similarityRangeHuman(1), fig5.similarityRangeHuman(2), fig5.similarityMatrixSizeMonkey(1), ...
    fig5.similarityMatrixSizeMonkey(2), fig5.featuresSizeMonkey(2), fig5.similarityRangeMonkey(1), ...
    fig5.similarityRangeMonkey(2)), 'rerun', ...
    ['Size and value range of the two concept-by-concept similarity matrices of Fig. 5: Pearson ' ...
    'correlations between the concepts'' 49 SPoSE features (human) and between their 49 monkey IT ' ...
    'component scores (monkey). The deep-network RDM is used in modules 03 and A3a.']);
rows(end + 1) = numbers_row('L3-003', sprintf(['highest: %s (rho = %.3f, rank 1 of %d); electronic / technology ' ...
    'rho = %.3f (rank %d of %d); lowest: %s (rho = %.3f)'], labels{mostMemorable}, ...
    fig5.memorabilityCorrelationsHuman(mostMemorable), numberOfFeatures, ...
    fig5.memorabilityCorrelationsHuman(electronics), memorabilityRanks(electronics), numberOfFeatures, ...
    labels{leastMemorable}, fig5.memorabilityCorrelationsHuman(leastMemorable)), 'rerun', ...
    sprintf(['Spearman correlation of each SPoSE feature with concept memorability over the %d concepts with ' ...
    'a score (Fig. 5a): the highest feature, electronic / technology with its rank, and the lowest feature. All 49 values are in outputs/figure_data/fig5a_ranked_feature_memorability.csv.'], ...
    fig5.numberOfConceptsWithScore));
rows(end + 1) = numbers_row('L3-004', sprintf('rho from %.3f to %.3f; tick labels (every fifth ranked feature): %s', ...
    fig5.rankedMemorabilityCorrelations(1), fig5.rankedMemorabilityCorrelations(end), ...
    strjoin(fig5.tickLabels, ' | ')), 'rerun', ...
    'Fig. 5a: the 49 SPoSE features ranked by their Spearman correlation with memorability and colored by rank (PiYG map, green highest, purple lowest); the range of the correlations and the tick labels.');
rows(end + 1) = numbers_row('L3-005', sprintf(['%d concepts on %d principal components of the %d features; ' ...
    'color = summed similarity, %.3f to %.3f (mean %.4f), color limits %.3f to %.3f; marker size %g to %g ' ...
    'points squared, growing linearly with conceptNumber (the position in the alphabetical THINGS concept ' ...
    'list)'], fig5.numberOfConcepts, fig5.numberOfPCs, numberOfFeatures, ...
    fig5.summedSimilarityRangeHuman(1), fig5.summedSimilarityRangeHuman(2), fig5.summedSimilarityMeanHuman, ...
    fig5.colorLimits(1), fig5.colorLimits(2), fig5.markerSizeRange(1), fig5.markerSizeRange(2)), 'rerun', ...
    ['Fig. 5b as drawn by the code: the 1,854 concepts on the first three principal components of the 49 SPoSE ' ...
    'features, colored by summed similarity (color limits 0.174 and 0.185); marker size grows with the concept''s position in the THINGS concept list; ' ...
    'the concepts face and chainsaw are marked and named (THINGS photographs are not included in the repository).']);
rows(end + 1) = numbers_row('L3-006', sprintf('%s; %d features', fig5.panelTextHuman, numberOfFeatures), 'rerun', ...
    'Fig. 5c: x = each feature''s Spearman correlation with summed similarity, y = its Spearman correlation with memorability; Pearson r across the 49 features.');
rows(end + 1) = numbers_row('L3-007', sprintf('%s; %d components', fig5.panelTextMonkey, fig5.featuresSizeMonkey(2)), 'rerun', ...
    'Fig. 5d: the same analysis with the 49 monkey IT components as the features (both axes).');
rows(end + 1) = numbers_row('L3-008', numberOfFeatures, 'rerun', 'Number of SPoSE features in Fig. 5.');
rows(end + 1) = numbers_row('L3-011', numberOfFeatures, 'rerun', 'Number of SPoSE features.');
rows(end + 1) = numbers_row('L3-014', sprintf(['body part-related: Spearman rho with summed similarity = %.3f, ' ...
    'rank %d of %d from the most negative (rank 1: %s, %.3f)'], ...
    fig5.summedSimilarityCorrelationsHuman(bodyPart), similarityRanks(bodyPart), numberOfFeatures, ...
    labels{similarityOrder(1)}, fig5.summedSimilarityCorrelationsHuman(similarityOrder(1))), 'rerun', ...
    ['Spearman correlation of the body part-related feature with summed similarity and its rank among the 49 features from the most ' ...
    'negative; a negative correlation means the feature predicts low summed similarity. All 49 values are in outputs/figure_data/fig5c_human_features_similarity_vs_memorability.csv.']);
rows(end + 1) = numbers_row('L3-019', sprintf(['most negative: %s %.3f, %s %.3f, %s %.3f; electronic / technology ' ...
    '%+.3f (rank %d of %d from the most negative); most positive: %s %+.3f'], ...
    labels{similarityOrder(1)}, fig5.summedSimilarityCorrelationsHuman(similarityOrder(1)), ...
    labels{similarityOrder(2)}, fig5.summedSimilarityCorrelationsHuman(similarityOrder(2)), ...
    labels{similarityOrder(3)}, fig5.summedSimilarityCorrelationsHuman(similarityOrder(3)), ...
    fig5.summedSimilarityCorrelationsHuman(electronics), similarityRanks(electronics), numberOfFeatures, ...
    labels{mostPositiveSimilarity}, fig5.summedSimilarityCorrelationsHuman(mostPositiveSimilarity)), 'rerun', ...
    'Spearman correlations of the SPoSE features with summed similarity (the x axis of Fig. 5c): the three most negative, electronic / technology with its rank, and the most positive.');
rows(end + 1) = numbers_row('L3-059', numberOfFeatures, 'rerun', 'Number of SPoSE features.');
rows(end + 1) = numbers_row('L3-060', numberOfFeatures, 'rerun', 'Number of SPoSE features.');
rows(end + 1) = numbers_row('L3-061', [fig5.numberOfPCs, numberOfFeatures], 'rerun', ...
    'Fig. 5b: number of principal components shown and number of SPoSE features.');
rows(end + 1) = numbers_row('L3-102', sprintf(['dissimilarity between two concepts: human %.3f to %.3f, monkey %.3f ' ...
    'to %.3f; kernel weight relative to a dissimilarity of 0: human %.2f to %.2f, monkey %.2f to %.2f (%.2f at a ' ...
    'dissimilarity of %d)'], fig5.dissimilarityRangeHuman(1), fig5.dissimilarityRangeHuman(2), ...
    fig5.dissimilarityRangeMonkey(1), fig5.dissimilarityRangeMonkey(2), fig5.kernelWeightRangeHuman(1), ...
    fig5.kernelWeightRangeHuman(2), fig5.kernelWeightRangeMonkey(1), fig5.kernelWeightRangeMonkey(2), ...
    fig5.kernelWeightAtLargestPossibleDissimilarity, fig5.largestPossibleDissimilarity), 'rerun', ...
    ['Dissimilarity: 1 minus the Pearson correlation of the feature rows of two different concepts, which can ' ...
    'run from 0 to 2. Kernel weight: normpdf(dissimilarity, 0, 2) / normpdf(0, 0, 2), the weight of a concept at ' ...
    'that dissimilarity in the summed similarity relative to a concept at a dissimilarity of 0.']);
rows(end + 1) = numbers_row('L3-103', sprintf(['%s: summed similarity %.4f (%.1f percent of the concepts lower, ' ...
    '%.1f percent higher); %s: %.4f (%.1f percent lower, %.1f percent higher); color scale %.3f (yellow) to ' ...
    '%.3f (dark blue)'], fig5.exampleConcepts{1}, fig5.exampleSummedSimilarity(1), fig5.examplePercentLower(1), ...
    fig5.examplePercentHigher(1), fig5.exampleConcepts{2}, fig5.exampleSummedSimilarity(2), ...
    fig5.examplePercentLower(2), fig5.examplePercentHigher(2), fig5.colorLimits(1), fig5.colorLimits(2)), 'rerun', ...
    ['Fig. 5b: the two concepts the caption names, marked and named in the panel, with their summed similarity ' ...
    '(the color of the panel, flipped parula) and the percent of the 1,854 concepts below and above it.']);
rows(end + 1) = numbers_row('L3-104', numberOfFeatures, 'rerun', ...
    sprintf(['Both spaces hold one row per concept and no image-level values: %d concepts x %d SPoSE features ' ...
    '(human) and %d concepts x %d IT components (monkey).'], fig5.numberOfConcepts, numberOfFeatures, ...
    fig5.featuresSizeMonkey(1), fig5.featuresSizeMonkey(2)));
rows(end + 1) = numbers_row('L3-105', fig5.r_human, 'rerun', ...
    sprintf('Fig. 5c panel text "%s": Pearson r across the 49 SPoSE features (the r of L3-009).', fig5.panelTextHuman));
rows(end + 1) = numbers_row('L3-106', fig5.r_monkey, 'rerun', ...
    sprintf('Fig. 5d panel text "%s": Pearson r across the 49 monkey IT components (the r of L3-010).', ...
    fig5.panelTextMonkey));
rows(end + 1) = numbers_row('L3-107', sprintf(['body part-related: memorability rho = %.3f (rank %d of %d), ' ...
    'summed-similarity rho = %.3f (rank %d of %d from the most negative); the most negative is %s ' ...
    '(memorability rank %d)'], fig5.memorabilityCorrelationsHuman(bodyPart), memorabilityRanks(bodyPart), ...
    numberOfFeatures, fig5.summedSimilarityCorrelationsHuman(bodyPart), similarityRanks(bodyPart), ...
    numberOfFeatures, labels{similarityOrder(1)}, memorabilityRanks(similarityOrder(1))), 'rerun', ...
    ['Restates L3-014: the Spearman correlations of the body part-related feature with memorability and with ' ...
    'summed similarity, their ranks among the 49 SPoSE features, and the feature most strongly linked to low ' ...
    'summed similarity.']);
rows(end + 1) = numbers_row('L3-108', sprintf(['restates Fig. 5c and 5d: %s across the %d SPoSE features (human), ' ...
    '%s across the %d IT components (monkey)'], fig5.panelTextHuman, numberOfFeatures, fig5.panelTextMonkey, ...
    fig5.featuresSizeMonkey(2)), 'rerun', 'Restates the Fig. 5c and 5d correlations (L3-009 and L3-010).');
rows(end + 1) = numbers_row('L3-109', sprintf(['body part-related rho = %.3f (rank %d of %d); electronic / ' ...
    'technology rho = %.3f (rank %d of %d)'], fig5.memorabilityCorrelationsHuman(bodyPart), ...
    memorabilityRanks(bodyPart), numberOfFeatures, fig5.memorabilityCorrelationsHuman(electronics), ...
    memorabilityRanks(electronics), numberOfFeatures), 'rerun', ...
    ['Spearman correlations of the body part-related and electronic / technology features with concept ' ...
    'memorability (Fig. 5a; the values of L3-003).']);
rows(end + 1) = numbers_row('L4-013', sprintf(['the two features most strongly linked to ' ...
    'low summed similarity are %s (%.3f) and %s (%.3f); their memorability ranks are %d and %d of %d'], ...
    labels{similarityOrder(1)}, fig5.summedSimilarityCorrelationsHuman(similarityOrder(1)), ...
    labels{similarityOrder(2)}, fig5.summedSimilarityCorrelationsHuman(similarityOrder(2)), ...
    memorabilityRanks(similarityOrder(1)), memorabilityRanks(similarityOrder(2)), numberOfFeatures), 'rerun', ...
    'The two SPoSE features with the most negative Spearman correlation with summed similarity, and their memorability ranks among the 49 features.');
rows(end + 1) = numbers_row('L5-045', [numberOfFeatures, fig5.numberOfConcepts], 'rerun', ...
    'Size of the SPoSE embedding: 49 features of 1,854 concepts (shared/things/spose_embedding_49d_sorted.txt, the same values as the features in shared/things/concept_info_human.mat).');
rows(end + 1) = numbers_row('L5-046', sprintf('%d x %d', fig5.similarityMatrixSizeHuman(1), fig5.similarityMatrixSizeHuman(2)), 'rerun', ...
    ['Size of the human similarity matrix: Pearson correlations between the ' ...
    'concepts'' SPoSE feature rows (the dissimilarity is 1 ' ...
    'minus this correlation).']);
rows(end + 1) = numbers_row('L5-047', sprintf(['%d of %d concepts have a score (%s has none); each equals the mean ' ...
    'of the public per-image scores of the concept (largest difference %.2g)'], fig5.numberOfConceptsWithScore, ...
    fig5.numberOfConcepts, fig5.conceptWithoutScore, fig5.largestDifferenceMemorability), 'rerun', ...
    'Number of concepts with a memorability score; each concept''s score is the mean of the public per-image corrected-recognition scores of its images (shared/things/things_images.csv; Kramer et al., 2023).');
rows(end + 1) = numbers_row('L5-048', sprintf('%d; IT; %.6g', ...
    monkeyVariance.componentsKept, monkeyVariance.percentKept), 'rerun', ...
    sprintf(['Number of principal components kept (%d), the brain area of the channels (IT, %d channels) and the ' ...
    'percent of the variance of the concept-averaged responses that these components keep (%.1f; T53), ' ...
    'computed from the eigenvalues in ' ...
    'shared/things/monkey_pca_explained.csv.'], ...
    monkeyVariance.componentsKept, monkeyVariance.numberOfComponents, monkeyVariance.percentKept), ...
    'code/monkey_variance_explained.m');
rows(end + 1) = numbers_row('L5-049', sprintf('%d x %d', fig5.similarityMatrixSizeMonkey(1), fig5.similarityMatrixSizeMonkey(2)), 'rerun', ...
    'Size of the monkey similarity matrix: Pearson correlations between the concepts'' 49 IT component scores.');
rows(end + 1) = numbers_row('L5-050', sprintf(['weights = image count of the other concept / %d (all THINGS images), ' ...
    'the concept itself left out; the rebuilt summed similarity equals the stored values (largest difference ' ...
    '%.2g human, %.2g monkey)'], fig5.totalImageCount, fig5.largestDifferenceHuman, fig5.largestDifferenceMonkey), 'rerun', ...
    'Weights of the summed similarity: the image count of each other concept in the concept tables (conceptCounts) divided by the 26,107 THINGS images, with the concept itself left out; the summed similarity rebuilt from the similarity matrices equals the values in the concept tables.');
rows(end + 1) = numbers_row('L5-051', [fig5.kernelCentreDissimilarity, fig5.kernelSD], 'rerun', ...
    ['Gaussian kernel of the summed similarity: center 0 in dissimilarity units ' ...
    '(a correlation of 1) and SD 2.']);
rows(end + 1) = numbers_row('L5-052', sprintf('one value per concept: human %d values, %.4f to %.4f; monkey %d values, %.4f to %.4f', ...
    fig5.numberOfConcepts, fig5.summedSimilarityRangeHuman(1), fig5.summedSimilarityRangeHuman(2), ...
    fig5.featuresSizeMonkey(1), fig5.summedSimilarityRangeMonkey(1), fig5.summedSimilarityRangeMonkey(2)), 'rerun', ...
    'Range of the full-THINGS summed similarity in the human and monkey spaces (one value per concept).');

%% 5. The rows that code/stats_fig5.py wrote into outputs/numbers.csv (the bootstrap statistics) are
% kept, so that the two parts of the module can run in either order
statisticsRows = rows_written_by_stats_fig5(fullfile(paths.outputs, 'numbers.csv'));
writtenRows = write_numbers_quietly([rows, statisticsRows], paths.outputs, scriptName);
matches = {writtenRows.match};
fprintf('\nnumbers.csv: %d rows; yes %d, no %d, documented %d\n', numel(writtenRows), ...
    sum(strcmp(matches, 'yes')), sum(strcmp(matches, 'no')), sum(strcmp(matches, 'documented')));
if isempty(statisticsRows)
    fprintf('code/stats_fig5.py adds the rows of the bootstrap statistics to outputs/numbers.csv\n');
else
    fprintf('including the %d rows of the bootstrap statistics written by code/stats_fig5.py\n', numel(statisticsRows));
end
% A judged value that does not match the printed value is listed and stops the run.
for rowIndex = 1:numel(writtenRows)
    if strcmp(writtenRows(rowIndex).match, 'no')
        fprintf('  %s: printed %s, computed %s\n', writtenRows(rowIndex).ledger_id, writtenRows(rowIndex).paper_value, ...
            writtenRows(rowIndex).computed_text);
    end
end
unexpectedMismatch = strcmp(matches, 'no');
if any(unexpectedMismatch)
    error('run_module:Mismatch', 'At least one computed value does not match the printed value.');
end
end


%% Local functions

function row = numbers_row(ledgerId, computedValue, mode, note, script)
% One row of outputs/numbers.csv (script: the script that computes the value; empty = the default,
% code/things_reanalysis.m)
if nargin < 5
    script = '';
end
row = struct('ledger_id', ledgerId, 'computed_value', computedValue, 'mode', mode, 'note', note, ...
    'script', script);
end

function statisticsRows = rows_written_by_stats_fig5(numbersFile)
% The rows of outputs/numbers.csv that code/stats_fig5.py wrote, with their computed value, mode, note
% and script (none when the file does not exist yet); write_numbers_csv.m judges them again
statisticsRows = struct('ledger_id', {}, 'computed_value', {}, 'mode', {}, 'note', {}, 'script', {});
if ~exist(numbersFile, 'file')
    return;
end
options = detectImportOptions(numbersFile, 'Delimiter', ',', 'TextType', 'char');
options = setvartype(options, options.VariableNames, 'char');
existingRows = readtable(numbersFile, options);
for rowIndex = 1:height(existingRows)
    if strcmp(existingRows.script{rowIndex}, 'code/stats_fig5.py')
        statisticsRows(end + 1) = numbers_row(existingRows.ledger_id{rowIndex}, ...
            existingRows.computed_value{rowIndex}, existingRows.mode{rowIndex}, existingRows.note{rowIndex}, ...
            existingRows.script{rowIndex}); %#ok<AGROW>
    end
end
end

function writtenRows = write_numbers_quietly(rows, outputsFolder, scriptName)
% Writes outputs/numbers.csv with shared/matlab/write_numbers_csv.m, which fills in the printed value,
% location and quote from shared/ledger/paper_numbers.csv and judges each match. That function's
% message (the full path of the file) is replaced by the file name relative to the module folder.
writtenRows = [];
evalc('writtenRows = write_numbers_csv(rows, outputsFolder, scriptName);');
fprintf('Wrote outputs/numbers.csv (%d rows)\n', numel(writtenRows));
end

function ranks = ranks_from_highest(values)
% 1 = the largest value
[~, order] = sort(values(:), 'descend');
ranks = zeros(numel(values), 1);
ranks(order) = (1:numel(values))';
end

function ranks = ranks_from_lowest(values)
% 1 = the smallest (most negative) value
[~, order] = sort(values(:), 'ascend');
ranks = zeros(numel(values), 1);
ranks(order) = (1:numel(values))';
end
