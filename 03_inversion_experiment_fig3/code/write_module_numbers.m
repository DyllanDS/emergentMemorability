function rows = write_module_numbers(results)
%WRITE_MODULE_NUMBERS  outputs/numbers.csv of module 03: one row per number of the paper this module
%   reproduces (24 ledger items). stats_fig3.py then adds the rows L2-014 and L2-015 (rho, its item
%   interval and p of Fig. 3e).
%
%   Input:  results, the struct run_module.m collects from the steps (design, flow, fig3)
%   Output: outputs/numbers.csv, written by shared/matlab/write_numbers_csv.m, which adds the
%           printed value, location and quote from shared/ledger/paper_numbers.csv and compares each
%           computed value with the printed one at the printed precision (round, exact, count);
%           statements without a printed number are listed as documented.
%   Every number in the computed values below comes from the results of this run; none is typed in.

paths = release_paths(mfilename('fullpath'));
design = results.design;
flow = results.flow;
fig3 = results.fig3;

scriptDesign = 'code/inversion_design_check.m';
scriptFlow = 'code/participant_flow.m';
scriptAnalysis = 'code/inversion_analysis.m';

similarTopToBottom = fliplr(design.similarItemsByQuintile);     % quintile 5 (highest scores) first
cutsText = strjoin(compose('%.4f', design.quintileCuts), ' / ');
rhoText = sprintf('Spearman rho = %.4f, p = %.5f (two-sided), over %d critical items and %d participants', ...
    fig3.rho, fig3.p, fig3.numberOfItems, fig3.participantsKept);

rows = struct('ledger_id', {}, 'computed_value', {}, 'mode', {}, 'note', {}, 'script', {});

%% The design (Fig. 3a to 3c; Methods, Behavioral Validation Experiments), counted in outputs/inversion_design_check.csv
rows(end + 1) = numbersRow('L2-003', sprintf(['%d critical items per block, one in each of %d bins of %g percent of the ' ...
    'published scores of %d THINGS images (cuts %s); one item per bin in all %d blocks'], design.criticalItemsPerBlock, ...
    design.numberOfQuintiles, design.binWidthPercent, design.numberOfScoredImages, cutsText, design.numberOfBlocks), ...
    'rerun', 'critical items per block, one from each fifth of the published scores of the THINGS images that have one', scriptDesign);
rows(end + 1) = numbersRow('L2-004', [similarTopToBottom(1), similarTopToBottom(end)], 'rerun', ...
    'similar items studied with the critical item of the highest and of the lowest memorability bin, in every block', scriptDesign);
rows(end + 1) = numbersRow('L2-005', design.similarItemsByQuintile, 'rerun', ...
    ['similar items studied with the critical items of memorability bins 1 (lowest 20 percent) to 5 (highest 20 percent), ' ...
    'counted in the study lists of every block'], scriptDesign);
rows(end + 1) = numbersRow('L2-006', design.studyItemsPerBlock, 'rerun', ...
    'images in each study list, in every block of the deployed lists and of every session', scriptDesign);
rows(end + 1) = numbersRow('L2-007', [design.testTrialsPerBlock, design.criticalItemsPerBlock, ...
    design.dissimilarItemsPerTestBlock, design.numberOfResponseOptions], 'rerun', ...
    'test trials per block; the critical and the maximally dissimilar items among them; response options used at test (1 = sure old to 6 = sure new)', scriptDesign);
rows(end + 1) = numbersRow('L2-011', [design.criticalItemsPerBlock, design.binWidthPercent, design.binWidthPercent, ...
    similarTopToBottom(1), similarTopToBottom(end)], 'rerun', ...
    'critical items per block; width in percent of the lowest and of the highest memorability bin; similar items studied with the critical item of the highest and of the lowest bin', scriptDesign);
rows(end + 1) = numbersRow('L5-025', [design.numberOfBlocks, design.criticalItemsPerBlock], 'rerun', ...
    'blocks per session; critical items per block', scriptDesign);
rows(end + 1) = numbersRow('L5-026', sprintf(['one critical item per bin of %g percent of the published scores ' ...
    '(%d bins; cuts %s), %d critical items in all'], design.binWidthPercent, design.numberOfQuintiles, cutsText, ...
    design.numberOfCriticalItems), 'rerun', 'one critical item per fifth of the published scores in each block; critical items over all blocks', scriptDesign);
rows(end + 1) = numbersRow('L5-027', similarTopToBottom, 'rerun', ...
    ['similar items studied with the critical item of each memorability bin, from the highest 20 percent to the lowest, ' ...
    'counted in the study lists of every block'], scriptDesign);
rows(end + 1) = numbersRow('L5-028', ['data/inversion_deployed_lists.csv lists the similar items chosen for each critical item in each block; ' ...
    'the deep-network similarity that chose them is not recomputed'], 'documented', ...
    'the stimulus-selection code is shared/things/provenance/SelectStimToFlipMemorability.m', scriptDesign);
rows(end + 1) = numbersRow('L5-029', [design.studyItemsPerBlock, design.controlledItemsPerList, ...
    design.similarItemsPerList, design.fillerItemsPerList, design.furtherStudiedItemsPerList], 'rerun', ...
    ['images per study list; controlled context items; similar items (0 + 1 + 2 + 4 + 8); non-similar exemplars ' ...
    'among the controlled items; further studied critical or maximally dissimilar items'], scriptDesign);
rows(end + 1) = numbersRow('L5-030', [design.blocksPerSession, design.studyItemsPerBlock, design.testTrialsPerBlock, ...
    design.criticalItemsPerBlock, design.dissimilarItemsPerTestBlock], 'rerun', ...
    'blocks per session; study images and test trials per block; critical and maximally dissimilar items per test block, in every session', scriptDesign);
rows(end + 1) = numbersRow('L5-031', design.numberOfResponseOptions, 'rerun', ...
    sprintf('response values used at test, 1 (sure old) to 6 (sure new): %s', strjoin(string(design.responseValues), ' ')), scriptDesign);
rows(end + 1) = numbersRow('L5-032', sprintf(['every critical item was studied (old) in %d to %d and a lure (new) in %d to %d of the ' ...
    '%d sessions; which %s of a block''s critical items a participant studied was drawn per participant and block'], ...
    design.timesOldRange(1), design.timesOldRange(2), design.timesNewRange(1), design.timesNewRange(2), ...
    design.numberOfSessions, strjoin(string(design.criticalStudiedPerBlock), ' or ')), 'documented', ...
    'sessions in which each critical item was studied and was a lure, counted from data/inversion_trials.csv', scriptDesign);
rows(end + 1) = numbersRow('L2-101', ['study display duration and interstimulus interval: settings of the experiment ' ...
    'software, not recorded in data/inversion_trials.csv (its only timing column is the response time of the test trials, rt_ms)'], ...
    'documented', 'presentation timing of the study stream', scriptDesign);

%% Participants (Methods, Experimental Procedures and Analysis)
flowNote = sprintf(['participants kept and excluded under the exclusion rules of the Methods, of %d sessions: excluded %d (one key on more than 80 percent of trials %d, more ' ...
    'than 20 percent of trials under 200 ms %d, more than 20 percent over 7,500 ms %d, hit rate minus false alarm rate ' ...
    'below 0.05 %d; %d meet more than one rule); the cap of 50 removes %d; kept %d'], flow.processed, flow.excluded, ...
    flow.sameKey, flow.tooFast, flow.tooSlow, flow.lowCr, flow.moreThanOneRule, flow.removedByCap, flow.kept);
rows(end + 1) = numbersRow('ADD-011a', [flow.kept, flow.excluded], 'rerun', flowNote, scriptFlow);

%% Fig. 3d and 3e
rows(end + 1) = numbersRow('L2-008', sprintf(['outputs/figures/fig3d_rank_order_lines.png: %d items ranked by published ' ...
    'score (left) and by CR over %d participants (right), highest at the top, green for the highest published scores'], ...
    fig3.numberOfItems, fig3.participantsKept), 'rerun', ...
    ['Fig. 3d: the critical items ranked by published memorability (left) and by corrected recognition in this task ' ...
    '(right), one line per item, rank 1 at the top, green for the highest published scores, ' ...
    'each end labeled with the concept name'], scriptAnalysis);
rows(end + 1) = numbersRow('L2-009', [fig3.rho, fig3.p, fig3.xTicks(1), fig3.xTicks(end), fig3.yTicks(1), fig3.yTicks(end)], ...
    'rerun', ['Spearman rho over the critical items between published memorability (Kramer et al., 2023) and corrected ' ...
    'recognition in this task, its two-sided p, and the first and last tick labels of the x and y axes of ' ...
    'outputs/figures/fig3e_memorability_vs_cr.png'], scriptAnalysis);
rows(end + 1) = numbersRow('L2-102', sprintf(['outputs/figures/fig3d_rank_order_lines.png: %d lines, one for each ' ...
    'critical item of the experiment, each labeled at both ends with its concept name'], fig3.numberOfItems), 'rerun', ...
    'Fig. 3d: one line per critical item (outputs/figure_data/fig3d_rank_order_lines.csv)', scriptAnalysis);
rows(end + 1) = numbersRow('L4-002', sprintf(['%s: the critical items with the highest published scores, studied ' ...
    'with the most similar items, ranked lowest in this task'], rhoText), 'restatement', 'the Fig. 3e rank correlation (L2-009) behind this General Discussion sentence', scriptAnalysis);
rows(end + 1) = numbersRow('L5-033', sprintf(['CR = hit rate minus false alarm rate of each critical item over the ' ...
    'kept participants ("old" = responses 1 to 3); %s'], rhoText), 'rerun', 'corrected recognition of each critical item and its Spearman rank correlation with the published scores (the computation behind L2-009)', scriptAnalysis);

%% The inversion in words (Abstract; Introduction; Inverting Memorability Through Direct Manipulation of Distinctiveness)
% rho and p of Fig. 3e, and the mean CR in this task of the critical items of each published memorability bin
meanCrByQuintile = zeros(1, design.numberOfQuintiles);
for quintile = 1:design.numberOfQuintiles
    meanCrByQuintile(quintile) = mean(fig3.items.cr(fig3.items.memorability_quintile == quintile));
end
inversionText = sprintf(['%s; mean CR in this task of the critical items of each published memorability bin, ' ...
    'from the lowest %g percent (%d similar items) to the highest %g percent (%d similar items): %s'], rhoText, ...
    design.binWidthPercent, design.similarItemsByQuintile(1), design.binWidthPercent, ...
    design.similarItemsByQuintile(end), strjoin(compose('%.3f', meanCrByQuintile), ', '));
rows(end + 1) = numbersRow('L2-103', inversionText, 'rerun', ...
    'the Fig. 3e rank correlation (L2-009) and the mean CR of each published memorability bin behind this Abstract sentence', scriptAnalysis);
rows(end + 1) = numbersRow('L2-104', inversionText, 'rerun', ...
    'the Fig. 3e rank correlation (L2-009) and the mean CR of each published memorability bin behind this Introduction sentence', scriptAnalysis);
rows(end + 1) = numbersRow('L2-105', inversionText, 'rerun', ...
    'the Fig. 3e rank correlation (L2-009, test T06) and the mean CR of each published memorability bin behind these two sentences', scriptAnalysis);

% the order of the rows (stats_fig3.py sorts the final file in ledger order)
ledgerOrder = {'ADD-011a', 'L2-003', 'L2-004', 'L2-005', 'L2-006', 'L2-007', 'L2-008', 'L2-009', 'L2-011', ...
    'L2-102', 'L2-103', 'L2-104', 'L2-105', 'L4-002', 'L5-025', 'L5-026', 'L5-027', 'L5-028', 'L5-029', 'L5-030', ...
    'L2-101', 'L5-031', 'L5-032', 'L5-033'};
position = zeros(1, numel(rows));
for rowIndex = 1:numel(rows)
    position(rowIndex) = find(strcmp(ledgerOrder, rows(rowIndex).ledger_id));
end
[~, order] = sort(position);
rows = rows(order);
if numel(unique({rows.ledger_id})) ~= numel(ledgerOrder)
    error('write_module_numbers:Coverage', 'numbers.csv must have one row for each of the %d ledger items of run_module.m', numel(ledgerOrder));
end

rows = write_numbers_csv(rows, paths.outputs, scriptAnalysis);
matchWords = {rows.match};
fprintf('numbers.csv: %d rows; %d yes, %d no, %d documented\n', numel(rows), sum(strcmp(matchWords, 'yes')), ...
    sum(strcmp(matchWords, 'no')), sum(strcmp(matchWords, 'documented')));
for rowIndex = 1:numel(rows)
    if strcmp(rows(rowIndex).match, 'no')
        fprintf('  %s: printed %s, computed %s (%s)\n', rows(rowIndex).ledger_id, rows(rowIndex).paper_value, ...
            rows(rowIndex).computed_text, rows(rowIndex).note);
    end
end
end


function row = numbersRow(ledgerId, computedValue, mode, note, script)
% one numbers.csv row (the printed value, location, quote and match type come from the ledger)
row = struct('ledger_id', ledgerId, 'computed_value', computedValue, 'mode', mode, 'note', note, 'script', script);
end
