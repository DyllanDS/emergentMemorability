function rows = write_module_numbers(results)
%WRITE_MODULE_NUMBERS  outputs/numbers.csv of module 06: one row per number of the paper it reproduces.
%
%   Input:  results, the struct run_module.m collects from the steps (sets, selection, design,
%           flow, fig6, fig7, fig7a, categories)
%   Output: outputs/numbers.csv, written by shared/matlab/write_numbers_csv.m, which adds the
%           printed value, location and quote from shared/ledger/paper_numbers.csv and judges each
%           computed value against the printed one (round, exact, count, less_than; figure
%           panels and descriptions are listed as documented, not judged).
%   Every number below comes from the results of this run. The rows of Fig. 6c to 6h (r, 95%
%   interval and bootstrap p) and the Methods row stating that no resample crosses zero come from
%   the participant bootstrap of stats_fig6_fig7.py, which adds them to outputs/numbers.csv.

paths = release_paths(mfilename('fullpath'));
sets = results.sets;
selection = results.selection;
design = results.design;
flow = results.flow;
fig6 = results.fig6;
fig7 = results.fig7;
fig7a = results.fig7a;
categories = results.categories;

% the six Fig. 6 correlations, in panel order c, d, e, f, g, h
panelOrder = {'c', 'd', 'e', 'f', 'g', 'h'};
r = zeros(1, 6);
for panelIndex = 1:6
    position = find(strcmp(fig6.panelLetters, panelOrder{panelIndex}));
    r(panelIndex) = fig6.r(position);
end

% slots per set (all three sets have the same number)
slotsPerSet = unique([sets.maintained.numberOfSlots, sets.changed.numberOfSlots, sets.reduced.numberOfSlots]);
if numel(slotsPerSet) ~= 1
    slotsPerSet = NaN;
end
keptPerSet = unique(flow.keptPerSet);
if numel(keptPerSet) ~= 1
    keptPerSet = NaN;
end

scriptFig6 = 'code/maintained_vs_changed.m';
scriptFig7 = 'code/maintained_vs_reduced_variance.m';
scriptFlow = 'code/participant_flow.m';
scriptSelection = 'code/reproduce_set_selection.m';
scriptDesign = 'code/check_task_design.m';
scriptSets = 'code/export_sampled_sets.m';
scriptPca = 'code/make_figure7a_pca.m';
scriptCategories = 'code/category_shares.m';

rows = struct('ledger_id', {}, 'computed_value', {}, 'mode', {}, 'note', {}, 'script', {}, ...
    'paper_value', {}, 'match_type', {});

%% Participants (Methods, Statistical Analysis and Exclusion Criteria; Participants)
flowNote = sprintf(['participants kept and excluded over the three image sets (%d sessions). Per set, sessions / excluded / kept: ' ...
    'maintained %d / %d / %d, changed %d / %d / %d, reduced %d / %d / %d. Participants meeting each rule, ' ...
    'maintained / changed / reduced: same key %d / %d / %d, too fast %d / %d / %d, too slow %d / %d / %d, ' ...
    'CR below 0.05 %d / %d / %d; %d meet more than one rule; the cap of 150 per set removes %d'], ...
    flow.total.processed, flow.maintained.processed, flow.maintained.excluded, flow.maintained.kept, ...
    flow.changed.processed, flow.changed.excluded, flow.changed.kept, flow.reduced.processed, ...
    flow.reduced.excluded, flow.reduced.kept, flow.maintained.sameKey, flow.changed.sameKey, ...
    flow.reduced.sameKey, flow.maintained.tooFast, flow.changed.tooFast, flow.reduced.tooFast, ...
    flow.maintained.tooSlow, flow.changed.tooSlow, flow.reduced.tooSlow, flow.maintained.lowCr, ...
    flow.changed.lowCr, flow.reduced.lowCr, flow.total.moreThanOneRule, flow.total.removedByCap);
rows(end + 1) = numbersRow('ADD-011c', [flow.total.kept, flow.total.excluded], scriptFlow, flowNote);
rows(end + 1) = numbersRow('L3-038', [keptPerSet, flow.total.kept, flow.total.excluded, flow.total.processed], scriptFlow, ...
    'participants kept per set; kept in total; excluded; sessions before exclusion, in the three image-set experiments');
rows(end + 1) = numbersRow('L5-071', [flow.total.kept, flow.keptPerSet], scriptFlow, ...
    'participants kept in total; maintained set; changed set; reduced set');
rows(end + 1) = numbersRow('L5-072', flow.total.excluded, scriptFlow, ...
    sprintf('participants excluded over the three image sets (maintained %d, changed %d, reduced %d)', flow.maintained.excluded, flow.changed.excluded, flow.reduced.excluded));
rows(end + 1) = numbersRow('L5-063', round(100 * flow.rules.oneKeyShareLimit, 10), scriptFlow, ...
    'percent of test trials with one response key above which a participant is excluded; checked against every participant''s flags');
rows(end + 1) = numbersRow('L5-064', [round(100 * flow.rules.rtShareLimit, 10), flow.rules.fastRtMs, flow.rules.slowRtMs], scriptFlow, ...
    'percent of test trials; fast and slow response-time limits in ms; checked against every participant''s flags');
rows(end + 1) = numbersRow('L5-065', flow.rules.minHitMinusFa, scriptFlow, ...
    'hit rate minus false alarm rate below which a participant is excluded; checked against every participant''s flags');
rows(end + 1) = numbersRow('L5-066', [flow.rules.trialMinRtMs, flow.rules.trialMaxRtMs], scriptFlow, ...
    'response-time window in ms of the trials kept after the exclusions; checked against the kept trials');

%% Task design (Methods, Recognition Memory Task)
rows(end + 1) = numbersRow('L5-073', design.blocksPerSession, scriptDesign, ...
    sprintf('study/test blocks in every one of the %d sessions', design.numberOfSessions));
rows(end + 1) = numbersRow('L5-074', [design.studyItemsPerBlock, design.testTrialsPerBlock, design.oldItemsPerBlock, ...
    design.newItemsPerBlock], scriptDesign, 'study images, test trials, old and new test items per block, the same in every block of every session');
rows(end + 1) = numbersRow('L5-075', design.ratingScalePoints, scriptDesign, 'response values used on the rating scale (1 = sure old to 6 = sure new)');
rows(end + 1) = numbersRow('L3-122', ['settings of the experiment software; the trial files in data/ hold the order of ' ...
    'the study and test trials, the responses and the response times'], scriptDesign, ...
    'presentation time of each study image and interstimulus interval of the three image-set experiments', '', '', ...
    'documented');
rows(end + 1) = numbersRow('L5-076', 'CR = hit rate minus false alarm rate, "old" = responses 1 to 3', scriptFig6, ...
    'the memory measure of every image-set analysis');

%% The image sets (Fig. 6 caption; Methods, Image Set Structure Manipulations)
rows(end + 1) = numbersRow('L3-028', [fig6.numberOfSetsCompared, slotsPerSet], scriptSets, 'image sets compared in Fig. 6; slots per image set (data/sampled_image_sets.mat)');
rows(end + 1) = numbersRow('L3-037', [slotsPerSet, fig6.numberOfSetsCompared], scriptSets, 'slots per image set; image sets compared in Fig. 6');
rows(end + 1) = numbersRow('L5-053', sprintf('maintained-set concepts redrawn from this score with rng(6) equal the set in data/sampled_image_sets.mat: %s', ...
    yesNo(selection.maintainedSetEqual)), scriptSelection, 'score = sum over the 49 features of feature value x sign(r) x r^2, r = Spearman correlation of the feature with full-THINGS summed similarity');
rows(end + 1) = numbersRow('L5-054', selection.numberOfMaintainedDraws, scriptSelection, ...
    sprintf('concepts drawn with replacement for the maintained set; the redrawn concepts equal the set in data/sampled_image_sets.mat: %s', yesNo(selection.maintainedSetEqual)));
rows(end + 1) = numbersRow('L3-124', sprintf('maintained set: its %d slots hold %d different THINGS images; %d of its %d concepts fill more than one slot', ...
    sets.maintained.numberOfSlots, sets.maintained.numberOfDistinctImages, sets.maintained.conceptsWithSeveralSlots, ...
    sets.maintained.numberOfConcepts), scriptSets, 'images of the maintained set in data/sampled_image_sets.mat');
rows(end + 1) = numbersRow('L5-055', sprintf('changed-set concepts redrawn with rng(6) equal the set in data/sampled_image_sets.mat: %s', ...
    yesNo(selection.changedSetEqual)), scriptSelection, 'score = - weighted values of the features positively correlated with full-THINGS memorability + weighted values of the negatively correlated features (weights: squared Spearman correlations)');
rows(end + 1) = numbersRow('L5-056', [selection.numberOfCandidateConcepts, selection.numberOfDissimilarConcepts], scriptSelection, ...
    sprintf('top-scoring candidate concepts; concepts chosen greedily for the changed set; the redrawn concepts equal the set in data/sampled_image_sets.mat: %s', yesNo(selection.changedSetEqual)));
rows(end + 1) = numbersRow('L5-057', selection.numberOfFurtherChangedConcepts, scriptSelection, ...
    sprintf('further concepts drawn with replacement for the changed set; the redrawn concepts equal the set in data/sampled_image_sets.mat: %s', yesNo(selection.changedSetEqual)));
rows(end + 1) = numbersRow('L5-058', [selection.numberOfExponents, selection.smallestExponent, selection.largestExponent, ...
    selection.exponentStep, selection.repetitionsPerExponent], scriptSelection, ...
    'candidate reduced sets; smallest exponent; largest exponent; step; repetitions of each exponent');
rows(end + 1) = numbersRow('L5-059', [selection.normalizedScoreRange, selection.numberOfReducedDraws], scriptSelection, ...
    'normalized concept score, lowest and highest; concepts drawn with replacement for each candidate set');
rows(end + 1) = numbersRow('L5-060', selection.numberOfCorrelationsPerCandidate, scriptSelection, ...
    sprintf('Spearman correlations (each feature with summed similarity, over the set''s slots) in each candidate''s composite score (their mean plus their maximum); the lowest composite score is candidate %d (exponent %.2f); the redrawn reduced set equals the set in data/sampled_image_sets.mat: %s', ...
    selection.chosenCandidate, selection.chosenExponent, yesNo(selection.reducedSetEqual)));

%% Fig. 6
rows(end + 1) = numbersRow('L3-020', sprintf(['%d concepts in the first %d principal components, %d of them in the ' ...
    'maintained set; marker size = share of the set''s slots, color = summed similarity to the set'], fig6.conceptsDrawn, ...
    fig6.nPrincipalComponents, fig6.conceptsPresent(1)), scriptFig6, 'Fig. 6a: outputs/figures/fig6a_pca_maintained_set.png');
rows(end + 1) = numbersRow('L3-021', sprintf(['%d concepts in the first %d principal components, %d of them in the ' ...
    'changed set; marker size = share of the set''s slots, color = summed similarity to the set'], fig6.conceptsDrawn, ...
    fig6.nPrincipalComponents, fig6.conceptsPresent(2)), scriptFig6, 'Fig. 6b: outputs/figures/fig6b_pca_changed_set.png');
rows(end + 1) = numbersRow('L3-030', [fig6.nPrincipalComponents, fig6.nFeatures], scriptFig6, ...
    'principal components shown in Fig. 6a, 6b; SPoSE features');
rows(end + 1) = numbersRow('L3-123', fig6.nFeatures, scriptFig6, ...
    'SPoSE features per concept; every analysis of the three image sets reads the one feature table of the 1,854 concepts (shared/things/concept_info_human.mat)');
rows(end + 1) = numbersRow('L4-005', r, scriptFig6, 'the six correlations of Fig. 6, panels c to h', '', '', ...
    'restatement');
rows(end + 1) = numbersRow('L3-127', [r(1), r(4)], scriptFig6, ['Pearson r across the 49 SPoSE features between the ' ...
    'full-THINGS memorability profile and the memorability profile of the maintained set (Fig. 6c); of the changed set (Fig. 6f)'], ...
    '', '', 'restatement');
rows(end + 1) = numbersRow('L5-082', fig6.nFeatures, scriptFig6, 'SPoSE features per concept');
rows(end + 1) = numbersRow('L5-083', 'Spearman correlation across concepts of each feature with concept CR (corr, Type Spearman, rows complete)', ...
    scriptFig6, 'feature-memorability profile of each set; ties get average ranks, and concepts without a score are left out');

%% Fig. 7
rows(end + 1) = numbersRow('L3-047', fig7.repMean, scriptFig7, 'maintained set: mean over its concepts of the within-set summed similarity (kernel normpdf(similarity, 1, 2); weights = the slot shares of the set after one slot of the concept itself is removed)');
rows(end + 1) = numbersRow('L3-048', fig7.repStd, scriptFig7, 'maintained set: SD (n - 1) over its concepts of the within-set summed similarity');
rows(end + 1) = numbersRow('L3-049', fig7.equatedStd, scriptFig7, sprintf('reduced set: SD (n - 1) over its concepts of the within-set summed similarity (mean %.5f)', fig7.equatedMean));
rows(end + 1) = numbersRow('L5-061', [fig7.equatedMean, fig7.equatedStd], scriptFig7, 'reduced set: mean; SD (n - 1) of the within-set summed similarity over its concepts');
rows(end + 1) = numbersRow('L5-062', [fig7.repMean, fig7.repStd], scriptFig7, 'maintained set: mean; SD (n - 1) of the within-set summed similarity over its concepts');
rows(end + 1) = numbersRow('L3-050', sprintf(['%d concepts in the first %d principal components of the %d features, ' ...
    '%d of them in the reduced set; marker size = share of the set''s slots, color = summed similarity to the set'], ...
    fig7a.conceptsDrawn, fig7a.nPrincipalComponents, fig7a.nFeatures, fig7a.conceptsInSet), scriptPca, ...
    'Fig. 7a: outputs/figures/fig7a_pca_reduced_set.png');
% Fig. 7b, 7c: the Mean and SD printed with each histogram, over the concepts in the set (the
% within-set summed similarity of maintained_vs_reduced_variance.m Part 2); the histograms plot the
% summed similarity of all 1,854 concepts to the set
rows(end + 1) = numbersRow('L3-051', [fig7.equatedMean, fig7.equatedStd], scriptFig7, ...
    sprintf('mean; SD (n - 1) over the %d concepts in the reduced set of their within-set summed similarity', ...
    fig7.conceptsInReduced));
rows(end + 1) = numbersRow('L3-052', [fig7.repMean, fig7.repStd], scriptFig7, ...
    sprintf('mean; SD (n - 1) over the %d concepts in the maintained set of their within-set summed similarity', ...
    fig7.conceptsInMaintained));
rows(end + 1) = numbersRow('L3-053', [fig7.summedRep, fig7.summedRepCi, fig7.summedEquated, fig7.summedEquatedCi], scriptFig7, ...
    sprintf('Fig. 7d bars: summed squared Spearman correlation of the 49 SPoSE features with concept CR, mean over %d participant resamples with its 2.5 and 97.5 percentiles; maintained set, then reduced set', fig7.nBootstraps));
reductionNote = sprintf(['SPoSE features; percent reduction of the summed squared feature-memorability correlation from the maintained to the reduced set (mean over %d participant resamples, rng(42)); one-sided ' ...
    'bootstrap p (share of resamples in which the reduced-set sum is at least the maintained-set sum)'], fig7.nBootstraps);
rows(end + 1) = numbersRow('L3-056', [fig7.nFeatures, fig7.percentReduction, fig7.pOneSided], scriptFig7, reductionNote);
rows(end + 1) = numbersRow('L3-057', [fig7.nFeatures, fig7.percentReduction, fig7.pOneSided], scriptFig7, reductionNote);
rows(end + 1) = numbersRow('L4-006', [fig7.percentReduction, fig7.pOneSided, fig7.repStd, fig7.equatedStd], scriptFig7, ...
    'Fig. 7: percent reduction; one-sided bootstrap p; SD of summed similarity in the maintained set; SD in the reduced set', '', '', 'restatement');
rows(end + 1) = numbersRow('L3-126', [fig7.percentReduction, fig7.pOneSided, fig7.repStd, fig7.equatedStd], scriptFig7, ...
    'Fig. 7: percent reduction; one-sided bootstrap p; SD of summed similarity in the maintained set; SD in the reduced set', '', '', 'restatement');
rows(end + 1) = numbersRow('L3-128', [fig7.percentReduction, fig7.pOneSided, fig7.repStd, fig7.equatedStd], scriptFig7, ...
    'Fig. 7: percent reduction; one-sided bootstrap p; SD of summed similarity in the maintained set; SD in the reduced set', '', '', 'restatement');
rows(end + 1) = numbersRow('L4-016', [fig7.percentReduction, fig7.pOneSided], scriptFig7, ...
    'Fig. 7d: percent reduction; one-sided bootstrap p', '', '', 'restatement');
rows(end + 1) = numbersRow('L5-084', [fig7.nBootstraps, fig7.nFeatures], scriptFig7, ...
    'participant resamples of the Fig. 7d bootstrap (rng(42); each draws the participants of each set with replacement); SPoSE features; one-sided p = share of resamples in which the reduced-set sum is at least the maintained-set sum');
rows(end + 1) = numbersRow('L3-125', sprintf(['Fig. 7d: one-sided bootstrap p = %.3f, the share of the %d participant ' ...
    'resamples in which the reduced-set sum is at least the maintained-set sum'], fig7.pOneSided, fig7.nBootstraps), ...
    scriptFig7, 'the test of the predicted reduction in Fig. 7d (test T19); the other tests of this module are two-sided');
rows(end + 1) = numbersRow('L3-062', fig7.nFeatures, scriptFig7, 'SPoSE features');
rows(end + 1) = numbersRow('L3-063', [fig7.numberOfSetsCompared, fig7a.nPrincipalComponents, fig7a.nFeatures], scriptPca, ...
    'image sets compared in Fig. 7; principal components shown in Fig. 7a; SPoSE features');

%% Category make-up (Reducing Variability In Distinctiveness Reduces Variability in Memorability; General Discussion)
rows(end + 1) = numbersRow('L3-058', [categories.largestPercentOfSlots, categories.secondPercentOfSlots], scriptCategories, ...
    sprintf(['percent of the reduced set''s %d slots in its two largest named higher-level categories, %s %.1f%% and ' ...
    '%s %.1f%% (%d named categories; category labels of shared/things/concept_table.csv); concepts ' ...
    'without a category %.1f%%; the largest share of the set''s concepts in one category is %.1f%% of %d; table in outputs/category_shares.csv'], ...
    categories.totalSlots, categories.largestCategory, categories.largestPercentOfSlots, categories.secondCategory, ...
    categories.secondPercentOfSlots, categories.numberOfNamedCategories, categories.noCategoryPercentOfSlots, ...
    categories.largestPercentOfConcepts, categories.conceptsInSet));
rows(end + 1) = numbersRow('L4-015', sprintf(['THINGS (%d concepts, %d images): tool %d concepts, %d images; ' ...
    'no face category among the %d named categories; the concept face (category %s) has %d images'], ...
    categories.numberOfConcepts, categories.numberOfImages, categories.toolConcepts, categories.toolImages, ...
    categories.numberOfNamedCategories, categories.faceConceptCategory, categories.faceConceptImages), scriptCategories, ...
    'concepts and images per higher-level THINGS category: outputs/things_category_sizes.csv', ...
    '', '', 'rerun');

rows = write_numbers_csv(rows, paths.outputs, 'code/run_module.m');
matches = {rows.match};
fprintf('numbers.csv: %d rows; yes %d, no %d, documented %d, none %d\n', numel(rows), sum(strcmp(matches, 'yes')), ...
    sum(strcmp(matches, 'no')), sum(strcmp(matches, 'documented')), sum(strcmp(matches, 'none')));
for rowIndex = 1:numel(rows)
    if strcmp(rows(rowIndex).match, 'no')
        fprintf('  NOT MATCHED: %s printed %s, computed %s\n', rows(rowIndex).ledger_id, rows(rowIndex).paper_value, ...
            rows(rowIndex).computed_text);
    end
end
end


function row = numbersRow(ledgerId, computedValue, script, note, paperValue, matchType, mode)
% One numbers.csv row. A paperValue or matchType that is not empty replaces the ledger's value;
% mode is 'rerun' unless given.
if nargin < 5
    paperValue = '';
end
if nargin < 6
    matchType = '';
end
if nargin < 7
    mode = 'rerun';
end
row = struct('ledger_id', ledgerId, 'computed_value', computedValue, 'mode', mode, 'note', note, ...
    'script', script, 'paper_value', paperValue, 'match_type', matchType);
end


function text = yesNo(flag)
if flag
    text = 'yes';
else
    text = 'no';
end
end
